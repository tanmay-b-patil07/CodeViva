// $2
export {};
EOF
}

# txt <path> <owner> <purpose>   plain text placeholder (prompt templates)
txt() {
  wf "$1" <<EOF
# Owner: $2. Placeholder created by scripts/scaffold.sh.
# Purpose: $3
EOF
}

echo "Scaffolding into: $ROOT"

