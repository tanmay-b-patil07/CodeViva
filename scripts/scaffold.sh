EOF
}

# comp <path> <Name>       React component placeholder
comp() {
  wf "$1" <<EOF
// Owner: Member 4. Placeholder created by scripts/scaffold.sh.
export function $2() {
  return null;
}
EOF
}

# ts <path> <purpose>      TypeScript module placeholder
ts() {
  wf "$1" <<EOF
