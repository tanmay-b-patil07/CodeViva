wf backend/alembic/env.py <<'EOF'
"""Alembic environment. Owner: Member 1.

Reads DATABASE_URL from the environment (or backend/.env if python-dotenv is installed).
Run alembic from the backend/ folder.
"""
import os
import sys
from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

try:  # optional: load backend/.env
    from dotenv import load_dotenv

    load_dotenv()
except ImportError:
    pass

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# Make autogenerate see the models once Member 1 has implemented them.
try:
    from app.db.base import Base
    import app.models  # noqa: F401

    target_metadata = Base.metadata
except ImportError as exc:
    print(f"[alembic env] models not importable yet, autogenerate disabled: {exc}", file=sys.stderr)
    target_metadata = None


def get_url() -> str:
    url = os.environ.get("DATABASE_URL")
    if not url:
        raise RuntimeError("DATABASE_URL is not set (see backend/.env.example)")
    return url


def run_migrations_offline() -> None:
    context.configure(
        url=get_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    section = config.get_section(config.config_ini_section, {})
    section["sqlalchemy.url"] = get_url()
    connectable = engine_from_config(section, prefix="sqlalchemy.", poolclass=pool.NullPool)
    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
EOF

