#!/usr/bin/env bash
# scripts/scaffold.sh
#
# Creates the frozen folder structure for the Code Comprehension project
# (see docs/FOLDER_STRUCTURE.md). Safe to re-run: it NEVER overwrites a file
# that already exists, it only creates what is missing.
#
# Usage (from anywhere inside the repo, needs bash: Git Bash / WSL / macOS / Linux):
#   bash scripts/scaffold.sh
#
# Optional: set the GitHub handles used in .github/CODEOWNERS
#   M1_GH=@alice M2_GH=@bob M3_GH=@carol M4_GH=@dave bash scripts/scaffold.sh

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
M1="${M1_GH:-@REPLACE-M1}"
M2="${M2_GH:-@REPLACE-M2}"
M3="${M3_GH:-@REPLACE-M3}"
M4="${M4_GH:-@REPLACE-M4}"

CREATED=0
SKIPPED=0

# ---------------------------------------------------------------- helpers

# wf <relative-path>   write stdin to the file unless it already exists
wf() {
  local target="$ROOT/$1"
  mkdir -p "$(dirname "$target")"
  if [[ -e "$target" ]]; then
    SKIPPED=$((SKIPPED + 1))
    cat > /dev/null
    return 0
  fi
  cat > "$target"
  CREATED=$((CREATED + 1))
}

# keep <relative-dir>  make an otherwise empty folder trackable by git
keep() { wf "$1/.gitkeep" < /dev/null; }

# py <path> <owner> <purpose>   python placeholder with a header docstring
py() {
  wf "$1" <<EOF
"""$3

Owner: $2
Placeholder created by scripts/scaffold.sh. Replace with real code.
"""
EOF
}

# sh_stub <path> <owner> <purpose>   executable shell placeholder
sh_stub() {
  wf "$1" <<EOF
#!/usr/bin/env bash
# Owner: $2. Placeholder created by scripts/scaffold.sh.
# Purpose: $3
echo "TODO: implement $1" >&2
exit 1
EOF
  chmod +x "$ROOT/$1"
}

# page <path> <label>      Next.js page placeholder
page() {
  wf "$1" <<EOF
// Owner: Member 4. Placeholder created by scripts/scaffold.sh.
export default function Page() {
  return <div>TODO: $2</div>;
}
EOF
}

# layout <path>            Next.js layout placeholder
layout() {
  wf "$1" <<EOF
// Owner: Member 4. Placeholder created by scripts/scaffold.sh.
// TODO: role guard for this portal (UX only, the API enforces real access).
export default function Layout({ children }: { children: React.ReactNode }) {
